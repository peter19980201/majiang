const assert = require('assert')
const definition = require('../../pages/calculator/definition')
const clone = value => JSON.parse(JSON.stringify(value))
global.wx = { showToast() {}, setNavigationBarTitle() {} }
const make = () => ({ ...definition, data: clone(definition.data), setData(patch) { Object.assign(this.data, patch) } })
const tap = (page, id, red = false) => page.selectTile({ currentTarget: { dataset: { id, red } } })
const remove = (page, index) => page.removeHandTile({ currentTarget: { dataset: { index } } })
for (const [id, flag] of [[4, 'redM5'], [13, 'redP5'], [22, 'redS5']]) {
  const page = make()
  tap(page, id, true)
  assert.deepStrictEqual(page.data.hand, [id])
  assert.deepStrictEqual(page.data.handRed, [true])
  assert(page.data[flag])
  assert.strictEqual(page.data.tileRemaining[id], 3)
  tap(page, id, true)
  assert.strictEqual(page.data.hand.length, 1)
  tap(page, id)
  remove(page, 1)
  assert(page.data[flag], 'removing a normal five must keep the red one')
  remove(page, 0)
  assert(!page.data[flag])
  page.setData({ inputTarget: 'agari' })
  tap(page, id, true)
  assert(page.data.agariRed && page.data[flag])
  tap(page, id)
  assert(!page.data.agariRed && !page.data[flag])
  tap(page, id, true)
  page.removeAgari()
  assert(!page.data[flag])
  page.setData({ inputTarget: 'hand' })
  for (let n = 0; n < 4; n++) tap(page, id)
  tap(page, id, true)
  assert.strictEqual(page.data.hand.length, 4)
  assert(!page.data[flag])
  page.clearHand()
  tap(page, id, true)
  page.clearHand()
  assert(!page.data[flag])
}
const page = make()
page.setData({ boardMode: true, hand: [0,1,2,3,4,5,10,11,12,19,20,22,22], agariTile: 21 })
page.updateRemaining()
page.doCalculate()
const normalHan = page.data.boardResult.han
page.setData({ handRed: page.data.hand.map((_, i) => i === 4) })
page.updateRemaining()
page.doCalculate()
assert.strictEqual(page.data.boardResult.han, normalHan + 1)
const saved = page.data.boardResult.calculatorInput
const restored = make()
restored.getOpenerEventChannel = () => ({ on(event, callback) { callback(saved) } })
restored.onLoad({ mode: 'board' })
assert(restored.data.handRed[4] && restored.data.redM5)
const legacy = clone(saved)
delete legacy.handRed
delete legacy.agariRed
const old = make()
old.getOpenerEventChannel = () => ({ on(event, callback) { callback(legacy) } })
old.onLoad({ mode: 'board' })
assert(old.data.handRed[4] && old.data.redM5)
console.log('Red-five entry passed: all suits, hand/agari insertion, duplicate and four-copy limits, removal, scoring and old/new restoration.')
